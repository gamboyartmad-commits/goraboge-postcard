// 글 안에서 처음 걸린 말을 돌려줌. 없으면 null
window.findBadWord = function findBadWord(text) {
  const { STRONG, TOKEN, ALLOW } = window.BAD_WORDS;
  let lower = String(text || '').toLowerCase();
  ALLOW.forEach((w) => { lower = lower.split(w).join(' '); });
  const squeezed = lower.replace(/[^가-힣ㄱ-ㅎㅏ-ㅣa-z]/g, '');
  const strong = STRONG.find((w) => squeezed.includes(w));
  if (strong) return strong;
  // '보지 않다', '자지 마'처럼 뒤에 않·안·마·말·못이 오면 보통 말이라 넘어감
  return TOKEN.find((w) => new RegExp(`(^|[^가-힣])${w}(?![가-힣])(?![^가-힣]*(않|안|마|말|못))`).test(lower)) || null;
};
